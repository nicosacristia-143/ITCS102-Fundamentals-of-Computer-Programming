#arithmetic operators

a = 6
b = 3

sum = a + b 
diff = a - b 
product = a * b 
quotient = a / b 
exponent = a ** b 
floor_div = a // b 
modulos = a % b 

print("the sum of", a, "and", b, "is", sum)
print("the difference of", a, "and", b, "is", diff)
print("the product of", a, "and", b, "is", product)
print("the quotient of", a, "and", b, "is", quotient)
print("the exponential value of", a, "and", b, "is", exponent)
print("the floor division of", a, "and", b, "is", floor_div)
print("the modulo of", a, "and", b, "is", modulos)
